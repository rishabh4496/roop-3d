@dataclass
class AnatomicalFullHeadAsset:
    """MakeHuman head, 60 orthogonal morphs, and rig-ready CC0 submeshes."""

    vertices: np.ndarray
    faces: np.ndarray
    morph_targets: np.ndarray  # (60, vertices, xyz), metres per unit coefficient
    morph_names: tuple[str, ...]
    submeshes: dict[str, AnatomicalSubmesh]
    soft_tissue_weights: np.ndarray
    legacy_shape_basis: np.ndarray | None = None
    uvs: np.ndarray | None = None
    license_id: str = LICENSE_ID
    template_source: str = "makehuman_cc0"
    _spring_filter: "SoftTissueSpringFilter" = field(default_factory=lambda: SoftTissueSpringFilter(), repr=False)

    def __post_init__(self) -> None:
        self.vertices = np.asarray(self.vertices, dtype=np.float32)
        self.faces = np.asarray(self.faces, dtype=np.int32)
        self.morph_targets = np.asarray(self.morph_targets, dtype=np.float32)
        self.morph_names = tuple(self.morph_names)
        self.soft_tissue_weights = np.asarray(self.soft_tissue_weights, dtype=np.float32)
        if self.vertices.ndim != 2 or self.vertices.shape[1] != 3 or not len(self.vertices):
            raise ValueError("vertices must have shape (N, 3)")
        if self.faces.ndim != 2 or self.faces.shape[1] != 3:
            raise ValueError("faces must have shape (F, 3)")
        if self.morph_targets.shape != (60, len(self.vertices), 3) or len(self.morph_names) != 60:
            raise ValueError("the anatomical pack requires exactly 60 named (N, 3) morph targets")
        if self.soft_tissue_weights.shape != (len(self.vertices),):
            raise ValueError("soft_tissue_weights must have shape (N,)")
        required = {"upper_teeth", "lower_teeth", "tongue", "eyeballs", "corneas", "eyelashes", "eyebrows", "hair_cards"}
        if not required.issubset(self.submeshes):
            raise ValueError(f"anatomical pack is missing submeshes: {sorted(required - set(self.submeshes))}")
        if self.submeshes["eyeballs"].uvs is None or self.submeshes["corneas"].uvs is None:
            raise ValueError("eyeball and cornea submeshes require UV coordinates")
        if self.submeshes["eyelashes"].alpha is None or self.submeshes["eyebrows"].alpha is None:
            raise ValueError("eyelash and eyebrow cards require alpha values")
        if not np.all(np.isfinite(self.vertices)) or not np.all(np.isfinite(self.morph_targets)):
            raise ValueError("anatomical geometry must be finite")

    @classmethod
    def from_template(
        cls,
        vertices: np.ndarray,
        faces: np.ndarray,
        *,
        uvs: np.ndarray | None = None,
        legacy_shape_basis: np.ndarray | None = None,
        template_source: str = "makehuman_cc0",
    ) -> "AnatomicalFullHeadAsset":
        """Extend any compatible head surface; useful for local synthesis and tests."""
        base = np.asarray(vertices, dtype=np.float64)
        tri = np.asarray(faces, dtype=np.int32)
        if base.ndim != 2 or base.shape[1] != 3 or len(base) < 16:
            raise ValueError("template must contain at least 16 xyz vertices")
        targets = _orthogonal_morph_targets(base)
        submeshes = _build_submeshes(base)
        weights = _soft_tissue_weights(base)
        return cls(base, tri, targets, MORPH_TARGET_NAMES, submeshes, weights,
                   legacy_shape_basis=legacy_shape_basis, uvs=uvs, template_source=template_source)

    @property
    def num_morphs(self) -> int:
        return len(self.morph_names)

    def morph(self, coefficients: Mapping[str, float] | np.ndarray | None = None) -> np.ndarray:
        """Return a deformed copy of the base head for named or positional coefficients."""
        if coefficients is None:
            return self.vertices.copy()
        if isinstance(coefficients, Mapping):
            unknown = set(coefficients) - set(self.morph_names)
            if unknown:
                raise ValueError(f"unknown anatomical morph target(s): {sorted(unknown)}")
            beta = np.zeros(60, dtype=np.float64)
            lookup = {name: index for index, name in enumerate(self.morph_names)}
            for name, value in coefficients.items():
                beta[lookup[name]] = float(value)
        else:
            beta = np.asarray(coefficients, dtype=np.float64).reshape(-1)
            if beta.shape != (60,):
                raise ValueError("morph coefficient array must have exactly 60 values")
        if not np.all(np.isfinite(beta)):
            raise ValueError("morph coefficients must be finite")
        return self.vertices + np.einsum("k,kvc->vc", beta, self.morph_targets, optimize=True)

    def articulate(self, theta_jaw: float = 0.0, psi_lip: float = 0.0) -> dict[str, np.ndarray]:
        """Pose the teeth and tongue using jaw opening radians and a lip/tongue scalar."""
        theta = float(np.clip(theta_jaw, 0.0, math.radians(75.0)))
        lip = float(np.clip(psi_lip, -1.0, 1.0))
        posed: dict[str, np.ndarray] = {}
        for name, mesh in self.submeshes.items():
            out = mesh.vertices.copy()
            if mesh.bone == "lower_jaw":
                out = _rotate_about_x(out, theta, _jaw_pivot(self.vertices))
            elif mesh.bone == "tongue":
                out = _rotate_about_x(out, theta * 0.72, _jaw_pivot(self.vertices))
                # Positive lip drive gently advances the tongue through the lip aperture.
                out[:, 2] -= lip * 0.006
                out[:, 1] += max(lip, 0.0) * 0.002
            posed[name] = out
        return posed

    def cornea_parallax_uv(
        self,
        uv: np.ndarray,
        view_direction: np.ndarray,
        *,
        iris_depth_m: float = 0.004,
        cornea_radius_m: float = 0.012,
        refractive_index: float = 1.376,
    ) -> np.ndarray:
        """Offset iris UVs using Snell refraction through a spherical cornea.

        ``view_direction`` points from the eye toward the camera in eye-local
        coordinates (the frontal direction is [0, 0, -1]).  The UV disk is
        centered at (.5, .5); output is clamped to that disk's square.
        """
        coords = np.asarray(uv, dtype=np.float64)
        view = np.asarray(view_direction, dtype=np.float64).reshape(3)
        if coords.shape[-1] != 2 or not np.all(np.isfinite(coords)):
            raise ValueError("uv must be finite with final dimension 2")
        if not np.all(np.isfinite(view)) or np.linalg.norm(view) < 1e-10:
            raise ValueError("view_direction must be a finite nonzero xyz vector")
        if iris_depth_m < 0 or cornea_radius_m <= 0 or refractive_index <= 1:
            raise ValueError("invalid cornea refraction parameters")
        view /= np.linalg.norm(view)
        p = (coords - 0.5) * 2.0
        r2 = np.sum(p * p, axis=-1)
        inside = r2 < 0.98
        z = -np.sqrt(np.maximum(1.0 - np.minimum(r2, 0.98), 1e-6))
        normal = np.stack((-p[..., 0], -p[..., 1], z), axis=-1)
        normal /= np.linalg.norm(normal, axis=-1, keepdims=True)
        incident = -view  # camera ray enters the cornea
        eta = 1.0 / float(refractive_index)
        cos_i = np.sum(normal * incident, axis=-1, keepdims=True)
        k = 1.0 - eta * eta * (1.0 - cos_i * cos_i)
        refracted = eta * incident - (eta * cos_i + np.sqrt(np.maximum(k, 0.0))) * normal
        z_forward = np.maximum(np.abs(refracted[..., 2]), 0.15)
        shift = (refracted[..., :2] / z_forward[..., None]) * (iris_depth_m / cornea_radius_m) * 0.5
        shift = np.where(inside[..., None], shift, 0.0)
        return np.clip(coords + shift, 0.0, 1.0).astype(np.float32)

    def apply_soft_tissue_spring(
        self,
        head_acceleration_6d: np.ndarray,
        dt: float,
        *,
        points: np.ndarray | None = None,
        weights: np.ndarray | None = None,
    ) -> np.ndarray:
        """Return secondary-motion offsets for the head or a rigged submesh."""
        positions = self.vertices if points is None else np.asarray(points, dtype=np.float64)
        blend = self.soft_tissue_weights if weights is None and points is None else weights
        if blend is None:
            blend = np.ones(len(positions), dtype=np.float64)
        return self._spring_filter.update(positions, head_acceleration_6d, dt, blend)

    @property
    def cavity_ao(self) -> "CavityAmbientOcclusion":
        return CavityAmbientOcclusion(self.vertices)

    def save(self, path: Path | str = DEFAULT_ASSET_PATH) -> Path:
        """Write a compressed, pickle-free asset and its CC0 provenance digest."""
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        arrays: dict[str, np.ndarray] = {
            "vertices": self.vertices,
            "faces": self.faces,
            "morph_targets": self.morph_targets,
            "morph_names": np.asarray(self.morph_names),
            "soft_tissue_weights": self.soft_tissue_weights,
            "metadata": np.asarray(json.dumps({
                "schema": SCHEMA,
                "license": self.license_id,
                "license_notice": LICENSE_NOTICE,
                "template_source": self.template_source,
                "morph_count": 60,
                "morph_amplitude_m": MORPH_AMPLITUDE_M,
                "rig_controls": {"jaw": "theta_jaw radians", "lip": "psi_lip in [-1, 1]"},
            }, sort_keys=True)),
        }
        if self.uvs is not None:
            arrays["uvs"] = np.asarray(self.uvs, dtype=np.float32)
        if self.legacy_shape_basis is not None:
            arrays["legacy_shape_basis"] = np.asarray(self.legacy_shape_basis, dtype=np.float32)
        for name, mesh in sorted(self.submeshes.items()):
            prefix = f"submesh__{name}__"
            arrays[prefix + "vertices"] = mesh.vertices.astype(np.float32)
            arrays[prefix + "faces"] = mesh.faces.astype(np.int32)
            arrays[prefix + "material"] = np.asarray(mesh.material)
            arrays[prefix + "bone"] = np.asarray(mesh.bone)
            for attr in ("uvs", "alpha", "spring_weights"):
                value = getattr(mesh, attr)
                if value is not None:
                    arrays[prefix + attr] = np.asarray(value, dtype=np.float32)
        np.savez_compressed(target, **arrays)
        sidecar = {
            "schema": SCHEMA,
            "license": self.license_id,
            "asset_digest": _arrays_digest(arrays),
            "vertices": int(len(self.vertices)),
            "faces": int(len(self.faces)),
            "morph_targets": 60,
            "submeshes": sorted(self.submeshes),
            "template_source": self.template_source,
        }
        target.with_name(target.name + ".json").write_text(
            json.dumps(sidecar, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
        )
        return target

    @classmethod
    def load(
        cls,
        path: Path | str | None = None,
        *,
        auto_build: bool = True,
        verify: bool = True,
    ) -> "AnatomicalFullHeadAsset":
        target = Path(path) if path is not None else DEFAULT_ASSET_PATH
        if not target.exists():
            if path is not None or not auto_build:
                raise DomainError("ANATOMICAL_PACK_MISSING", f"{target} is not available", 404)
            build_anatomical_pack(target)
        try:
            with np.load(target, allow_pickle=False) as data:
                arrays = {key: data[key] for key in data.files}
            metadata = json.loads(str(arrays["metadata"].item()))
            if metadata.get("schema") != SCHEMA or metadata.get("license") != LICENSE_ID:
                raise ValueError("unsupported schema or license declaration")
            if verify:
                sidecar = json.loads(target.with_name(target.name + ".json").read_text("utf-8"))
                if sidecar.get("asset_digest") != _arrays_digest(arrays):
                    raise ValueError("content digest mismatch")
            submeshes: dict[str, AnatomicalSubmesh] = {}
            prefixes = {key.split("__", 2)[1] for key in arrays if key.startswith("submesh__")}
            for name in sorted(prefixes):
                prefix = f"submesh__{name}__"
                submeshes[name] = AnatomicalSubmesh(
                    name=name,
                    vertices=arrays[prefix + "vertices"],
                    faces=arrays[prefix + "faces"],
                    material=str(arrays[prefix + "material"].item()),
                    bone=str(arrays[prefix + "bone"].item()),
                    uvs=arrays.get(prefix + "uvs"),
                    alpha=arrays.get(prefix + "alpha"),
                    spring_weights=arrays.get(prefix + "spring_weights"),
                )
            return cls(
                vertices=arrays["vertices"],
                faces=arrays["faces"],
                morph_targets=arrays["morph_targets"],
                morph_names=tuple(str(item) for item in arrays["morph_names"].tolist()),
                submeshes=submeshes,
                soft_tissue_weights=arrays["soft_tissue_weights"],
                legacy_shape_basis=arrays.get("legacy_shape_basis"),
                uvs=arrays.get("uvs"),
                license_id=metadata["license"],
                template_source=metadata.get("template_source", "makehuman_cc0"),
            )
        except (OSError, ValueError, KeyError, json.JSONDecodeError) as error:
            raise DomainError("ANATOMICAL_PACK_CORRUPT", f"Could not verify {target}: {error}", 422) from error


class CavityAmbientOcclusion:
    """Analytic occlusion fields for the oral cavity and both nostrils.

    Returned values are AO darkness in [0, 1]. Oral occlusion falls smoothly
    with jaw opening; nasal occlusion is independent of jaw motion.
    """

    def __init__(self, head_vertices: np.ndarray):
        vertices = np.asarray(head_vertices, dtype=np.float64)
        self.minimum = vertices.min(axis=0)
        self.maximum = vertices.max(axis=0)
        span = np.maximum(self.maximum - self.minimum, 1e-4)
        self.span = span
        self.front_z = float(self.minimum[2])
        self.mouth_center = np.array([0.0, self.minimum[1] + 0.72 * span[1], self.front_z + 0.22 * span[2]])
        self.nostril_centers = np.array([
            [-0.010, self.minimum[1] + 0.47 * span[1], self.front_z + 0.13 * span[2]],
            [0.010, self.minimum[1] + 0.47 * span[1], self.front_z + 0.13 * span[2]],
        ])

    def evaluate(
        self,
        theta_jaw: float,
        points: np.ndarray | None = None,
        *,
        cavity: str = "oral",
    ) -> np.ndarray | float:
        theta = float(np.clip(theta_jaw, 0.0, math.radians(75.0)))
        if cavity == "oral":
            center = self.mouth_center
            scale = self.span * np.array([0.25, 0.15, 0.20])
            opening = math.sin(theta)
            strength = 0.96 * (1.0 - opening) ** 1.35
        elif cavity in {"nostril", "nostrils"}:
            if points is None:
                return np.full(2, 0.72, dtype=np.float32)
            samples = np.asarray(points, dtype=np.float64)
            d = samples[..., None, :] - self.nostril_centers
            scale = self.span * np.array([0.075, 0.065, 0.10])
            weights = np.exp(-0.5 * np.sum((d / scale) ** 2, axis=-1))
            return np.clip(0.72 * np.max(weights, axis=-1), 0.0, 1.0).astype(np.float32)
        else:
            raise ValueError("cavity must be 'oral' or 'nostrils'")
        if points is None:
            return float(strength)
        samples = np.asarray(points, dtype=np.float64)
        if samples.shape[-1] != 3:
            raise ValueError("cavity sample points must end in xyz")
        spatial = np.exp(-0.5 * np.sum(((samples - center) / scale) ** 2, axis=-1))
        return np.clip(strength * spatial, 0.0, 1.0).astype(np.float32)

    def evaluate_both(self, theta_jaw: float, oral_points: np.ndarray, nostril_points: np.ndarray) -> dict[str, np.ndarray | float]:
        return {
            "oral": self.evaluate(theta_jaw, oral_points, cavity="oral"),
            "nostrils": self.evaluate(theta_jaw, nostril_points, cavity="nostrils"),
        }


class SoftTissueSpringFilter:
    """Exact-step critically damped filter from 6DoF head acceleration to offsets.

    The six input components are linear acceleration xyz (m/s²) followed by
    angular acceleration xyz (rad/s²). The resulting inertial target is
    low-pass filtered with the closed-form critically damped step, avoiding
    Euler instability when a render frame is late.
    """

    def __init__(self, natural_frequency_hz: float = 5.0, gain: float = 0.85):
        if natural_frequency_hz <= 0 or gain < 0:
            raise ValueError("frequency must be positive and gain nonnegative")
        self.omega = 2.0 * math.pi * float(natural_frequency_hz)
        self.gain = float(gain)
        self._offset: np.ndarray | None = None
        self._velocity: np.ndarray | None = None

    def reset(self) -> None:
        self._offset = None
        self._velocity = None

    def update(
        self,
        points: np.ndarray,
        head_acceleration_6d: np.ndarray,
        dt: float,
        weights: np.ndarray | None = None,
    ) -> np.ndarray:
        positions = np.asarray(points, dtype=np.float64)
        accel = np.asarray(head_acceleration_6d, dtype=np.float64).reshape(-1)
        if positions.ndim != 2 or positions.shape[1] != 3 or accel.shape != (6,):
            raise ValueError("points must be (N, 3) and head_acceleration_6d must have 6 values")
        if not np.all(np.isfinite(positions)) or not np.all(np.isfinite(accel)) or not math.isfinite(dt) or dt <= 0:
            raise ValueError("spring inputs must be finite and dt positive")
        blend = np.ones(len(positions), dtype=np.float64) if weights is None else np.asarray(weights, dtype=np.float64).reshape(-1)
        if blend.shape != (len(positions),) or not np.all(np.isfinite(blend)):
            raise ValueError("weights must be finite and match the point count")
        blend = np.clip(blend, 0.0, 1.0)
        lever = positions - positions.mean(axis=0, keepdims=True)
        linear = accel[:3]
        angular = accel[3:]
        inertial = linear[None, :] + np.cross(np.broadcast_to(angular, lever.shape), lever)
        target = -self.gain * inertial / (self.omega * self.omega)
        target *= blend[:, None]
        if self._offset is None or self._offset.shape != target.shape:
            self._offset = np.zeros_like(target)
            self._velocity = np.zeros_like(target)
        assert self._velocity is not None
        # Exact solution for a held target during dt with critical damping.
        decay = math.exp(-self.omega * dt)
        delta = self._offset - target
        c = self._velocity + self.omega * delta
        self._offset = target + (delta + c * dt) * decay
        self._velocity = (self._velocity - self.omega * c * dt) * decay
        return self._offset.astype(np.float32, copy=True)


def _arrays_digest(arrays: Mapping[str, np.ndarray]) -> str:
    digest = hashlib.sha256()
    for key in sorted(arrays):
        value = np.ascontiguousarray(arrays[key])
        digest.update(key.encode("utf-8"))
        digest.update(str(value.dtype).encode("ascii") + str(value.shape).encode("ascii"))
        digest.update(value.tobytes() if value.dtype.kind != "U" else "|".join(value.tolist()).encode("utf-8"))
    return digest.hexdigest()


def _orthogonal_morph_targets(vertices: np.ndarray) -> np.ndarray:
    """Create smooth, localized semantic displacement fields then orthogonalize them."""
    points = np.asarray(vertices, dtype=np.float64)
    lo, hi = points.min(axis=0), points.max(axis=0)
    span = np.maximum(hi - lo, 1e-4)
    mid = (lo + hi) * 0.5
    z_front = lo[2]
    h, w, d = span[1], span[0], span[2]
    regions: dict[str, tuple[np.ndarray, np.ndarray, bool]] = {
        "forehead": (np.array([0.0, lo[1] + 0.19 * h, mid[2]]), np.array([0.37 * w, 0.20 * h, 0.62 * d]), False),
        "temples": (np.array([0.0, lo[1] + 0.33 * h, mid[2]]), np.array([0.76 * w, 0.20 * h, 0.53 * d]), True),
        "zygoma": (np.array([0.0, lo[1] + 0.51 * h, z_front + 0.23 * d]), np.array([0.70 * w, 0.17 * h, 0.38 * d]), True),
        "nose": (np.array([0.0, lo[1] + 0.47 * h, z_front + 0.14 * d]), np.array([0.24 * w, 0.25 * h, 0.31 * d]), False),
        "mandible": (np.array([0.0, lo[1] + 0.75 * h, z_front + 0.26 * d]), np.array([0.75 * w, 0.22 * h, 0.50 * d]), True),
        "ears": (np.array([0.0, lo[1] + 0.53 * h, mid[2]]), np.array([0.91 * w, 0.25 * h, 0.72 * d]), True),
        "neck": (np.array([0.0, hi[1] - 0.045 * h, mid[2]]), np.array([0.45 * w, 0.23 * h, 0.61 * d]), False),
        "craniofacial": (np.array([0.0, lo[1] + 0.36 * h, mid[2]]), np.array([0.76 * w, 0.57 * h, 0.71 * d]), False),
    }
    x = (points[:, 0] - mid[0]) / (0.5 * w)
    y = (points[:, 1] - mid[1]) / (0.5 * h)
    z = (points[:, 2] - mid[2]) / (0.5 * d)
    coord = (x, y, z)
    per_group_index = {key: 0 for key in MORPH_GROUPS}
    orthogonal: list[np.ndarray] = []
    targets: list[np.ndarray] = []
    for group, names in MORPH_GROUPS.items():
        center, sigma, bilateral = regions[group]
        if bilateral:
            centers = [center.copy(), center.copy()]
            centers[0][0] = -max(abs(center[0]), 0.45 * w)
            centers[1][0] = max(abs(center[0]), 0.45 * w)
        else:
            centers = [center]
        support = np.zeros(len(points), dtype=np.float64)
        for c in centers:
            support += np.exp(-0.5 * np.sum(((points - c) / (sigma + 1e-8)) ** 2, axis=1))
        support = np.minimum(support, 1.0)
        for name in names:
            mode = per_group_index[group]
            per_group_index[group] += 1
            exponent = _monomial_exponent(mode)
            feature = np.ones(len(points), dtype=np.float64)
            for axis, power in enumerate(exponent):
                if power:
                    feature *= coord[axis] ** power
            # Avoid a near-zero mean displacement and give each axis a coherent local shape.
            feature -= np.average(feature, weights=support + 1e-12)
            mode_name = name.casefold()
            if any(token in mode_name for token in ("width", "spacing", "taper")):
                direction = np.stack((np.sign(x), 0.10 * y, 0.0 * z), axis=1)
            elif any(token in mode_name for token in ("height", "length", "ramus")):
                direction = np.stack((0.0 * x, np.ones_like(y), 0.0 * z), axis=1)
                if "forehead" in mode_name or "cranial" in mode_name:
                    direction[:, 1] *= -1.0
            elif any(token in mode_name for token in ("projection", "protrusion", "depth", "bossing", "fullness", "convexity")):
                direction = np.stack((0.08 * x, 0.0 * y, -np.ones_like(z)), axis=1)
            elif any(token in mode_name for token in ("slope", "angle", "rotation", "arch")):
                direction = np.stack((-y, x, 0.12 * z), axis=1)
            elif "asymmetry" in mode_name or "deviation" in mode_name:
                direction = np.stack((np.ones_like(x), 0.12 * y, 0.08 * z), axis=1)
            elif any(token in mode_name for token in ("hollow", "recession", "flatness", "concavity")):
                direction = np.stack((-0.05 * x, 0.0 * y, np.ones_like(z)), axis=1)
            else:
                direction = np.stack((x, 0.35 * y, -0.50 * np.ones_like(z)), axis=1)
            candidate = (support * feature)[:, None] * direction
            flat = candidate.reshape(-1)
            raw_norm = np.linalg.norm(flat)
            if raw_norm < 1e-10:
                raise ValueError(f"template has no support for {name}")
            residual = flat.copy()
            # Modified Gram-Schmidt in float64 ensures the exported targets are orthogonal.
            for q in orthogonal:
                residual -= np.dot(residual, q) * q
            norm = np.linalg.norm(residual)
            if norm < raw_norm * 1e-8:
                # Deterministic, smooth fallback mode for unusually sparse/low-resolution templates.
                rng = np.random.default_rng(9700 + len(orthogonal))
                noise = rng.standard_normal((len(points), 3))
                smooth = np.stack((np.sin((mode + 1.3) * x), np.cos((mode + 0.7) * y),
                                   np.sin((mode + 2.1) * z)), axis=1)
                residual = (support[:, None] * (noise * 0.15 + smooth)).reshape(-1)
                for q in orthogonal:
                    residual -= np.dot(residual, q) * q
                norm = np.linalg.norm(residual)
            if norm < 1e-10:
                raise ValueError(f"could not construct independent target {name}")
            q = residual / norm
            orthogonal.append(q)
            field = q.reshape(-1, 3)
            maximum = np.linalg.norm(field, axis=1).max()
            targets.append(field * (MORPH_AMPLITUDE_M / max(maximum, 1e-12)))
    return np.asarray(targets, dtype=np.float32)


def _monomial_exponent(index: int) -> tuple[int, int, int]:
    """Enumerate low-degree 3D monomials deterministically, excluding the constant."""
    candidates: list[tuple[int, int, int]] = []
    degree = 1
    while len(candidates) <= index:
        for a in range(degree, -1, -1):
            for b in range(degree - a, -1, -1):
                c = degree - a - b
                candidates.append((a, b, c))
        degree += 1
    return candidates[index]


def _soft_tissue_weights(vertices: np.ndarray) -> np.ndarray:
    points = np.asarray(vertices, dtype=np.float64)
    lo, hi = points.min(axis=0), points.max(axis=0)
    span = np.maximum(hi - lo, 1e-4)
    centers = [
        np.array([side * 0.36 * span[0], lo[1] + 0.67 * span[1], lo[2] + 0.25 * span[2]])
        for side in (-1.0, 1.0)
    ]
    cheek = sum(np.exp(-0.5 * np.sum(((points - c) / (span * [0.22, 0.16, 0.24])) ** 2, axis=1)) for c in centers)
    jowl_centers = [np.array([side * 0.32 * span[0], lo[1] + 0.79 * span[1], lo[2] + 0.30 * span[2]]) for side in (-1.0, 1.0)]
    jowl = sum(np.exp(-0.5 * np.sum(((points - c) / (span * [0.25, 0.13, 0.25])) ** 2, axis=1)) for c in jowl_centers)
    submental = np.exp(-0.5 * np.sum(((points - np.array([0.0, lo[1] + 0.89 * span[1], lo[2] + 0.45 * span[2]])) /
                                       (span * [0.28, 0.10, 0.22])) ** 2, axis=1))
    return np.clip(np.maximum.reduce([cheek, jowl, submental]), 0.0, 1.0).astype(np.float32)


def _build_submeshes(vertices: np.ndarray) -> dict[str, AnatomicalSubmesh]:
    points = np.asarray(vertices, dtype=np.float64)
    lo, hi = points.min(axis=0), points.max(axis=0)
    span = np.maximum(hi - lo, 1e-4)
    mouth_y = lo[1] + 0.72 * span[1]
    mouth_z = lo[2] + 0.20 * span[2]
    pivot = np.array([0.0, mouth_y - 0.006, mouth_z + 0.016])
    upper_teeth = _tooth_row(mouth_y - 0.006, mouth_z, span, upper=True)
    lower_teeth = _tooth_row(mouth_y + 0.010, mouth_z + 0.003, span, upper=False)
    tongue = _ellipsoid_mesh(np.array([0.0, mouth_y + 0.004, mouth_z + 0.012]),
                             np.array([0.016, 0.007, 0.024]), rings=12, segments=18)
    # Eye locations are derived from the upper frontal head profile, not from a model package.
    eye_y = lo[1] + 0.39 * span[1]
    eye_z = lo[2] + 0.11 * span[2]
    eye_centers = [np.array([side * 0.031, eye_y, eye_z]) for side in (-1.0, 1.0)]
    eye_meshes = [_ellipsoid_mesh(center, np.array([0.012, 0.012, 0.012]), 14, 20) for center in eye_centers]
    eyes = _combine_meshes(eye_meshes)
    eye_uvs = np.concatenate([_sphere_uvs(mesh[0], center) for mesh, center in zip(eye_meshes, eye_centers)])
    cornea_centers = [center + np.array([0.0, 0.0, -0.010]) for center in eye_centers]
    cornea_meshes = [_ellipsoid_mesh(center, np.array([0.007, 0.007, 0.003]), 10, 18) for center in cornea_centers]
    corneas = _combine_meshes(cornea_meshes)
    cornea_uvs = np.concatenate([_sphere_uvs(mesh[0], center) for mesh, center in zip(cornea_meshes, cornea_centers)])
    lashes = _alpha_strips([(-0.044, eye_y - 0.014, eye_z - 0.001, 0.026),
                            (0.018, eye_y - 0.014, eye_z - 0.001, 0.026)], thickness=0.0025, steps=8)
    brows = _alpha_strips([(-0.051, eye_y - 0.027, eye_z + 0.001, 0.032),
                           (0.019, eye_y - 0.027, eye_z + 0.001, 0.032)], thickness=0.004, steps=10)
    hair = _hair_cards(lo, hi)
    return {
        "upper_teeth": AnatomicalSubmesh("upper_teeth", *upper_teeth, material="enamel", bone="head"),
        "lower_teeth": AnatomicalSubmesh("lower_teeth", *lower_teeth, material="enamel", bone="lower_jaw"),
        "tongue": AnatomicalSubmesh("tongue", *tongue, material="tongue", bone="tongue"),
        "eyeballs": AnatomicalSubmesh("eyeballs", *eyes, material="sclera_iris_cornea", bone="head", uvs=eye_uvs),
        "corneas": AnatomicalSubmesh("corneas", *corneas, material="cornea_refraction_ior_1.376", bone="head", uvs=cornea_uvs),
        "eyelashes": AnatomicalSubmesh("eyelashes", *lashes[:2], material="alpha_lash", bone="head", uvs=lashes[2], alpha=lashes[3]),
        "eyebrows": AnatomicalSubmesh("eyebrows", *brows[:2], material="alpha_brow", bone="head", uvs=brows[2], alpha=brows[3]),
        "hair_cards": AnatomicalSubmesh("hair_cards", *hair[:2], material="alpha_hair", bone="head", uvs=hair[2], alpha=hair[3],
                                       spring_weights=np.ones(len(hair[0]), dtype=np.float32)),
    }


def _tooth_row(y: float, z: float, span: np.ndarray, *, upper: bool) -> tuple[np.ndarray, np.ndarray]:
    meshes = []
    count = 14
    radius_x = min(0.0047, span[0] * 0.034)
    radius_y = min(0.0060, span[1] * 0.036)
    radius_z = min(0.0042, span[2] * 0.045)
    for index in range(count):
        x = (index - (count - 1) / 2) * radius_x * 1.55
        arch = (x / max(span[0] * 0.28, 1e-4)) ** 2
        center = np.array([x, y + 0.003 * arch * (1 if upper else -1), z + 0.010 * arch])
        meshes.append(_ellipsoid_mesh(center, np.array([radius_x, radius_y, radius_z]), 7, 10))
    return _combine_meshes(meshes)


def _ellipsoid_mesh(center: np.ndarray, radii: np.ndarray, rings: int, segments: int) -> tuple[np.ndarray, np.ndarray]:
    vertices = [center + np.array([0.0, -radii[1], 0.0])]
    for ring in range(1, rings):
        theta = math.pi * ring / rings
        for segment in range(segments):
            phi = 2 * math.pi * segment / segments
            vertices.append(center + np.array([radii[0] * math.sin(theta) * math.cos(phi),
                                                -radii[1] * math.cos(theta),
                                                radii[2] * math.sin(theta) * math.sin(phi)]))
    bottom = len(vertices)
    vertices.append(center + np.array([0.0, radii[1], 0.0]))
    faces: list[tuple[int, int, int]] = []
    for j in range(segments):
        faces.append((0, 1 + j, 1 + (j + 1) % segments))
    for ring in range(rings - 2):
        a = 1 + ring * segments
        b = a + segments
        for j in range(segments):
            j1 = (j + 1) % segments
            faces.extend(((a + j, b + j, a + j1), (a + j1, b + j, b + j1)))
    last = 1 + (rings - 2) * segments
    for j in range(segments):
        faces.append((last + j, bottom, last + (j + 1) % segments))
    return np.asarray(vertices, dtype=np.float32), np.asarray(faces, dtype=np.int32)


def _combine_meshes(meshes: list[tuple[np.ndarray, np.ndarray]]) -> tuple[np.ndarray, np.ndarray]:
    verts, faces, offset = [], [], 0
    for v, f in meshes:
        verts.append(v)
        faces.append(f + offset)
        offset += len(v)
    return np.concatenate(verts, axis=0), np.concatenate(faces, axis=0)


def _sphere_uvs(vertices: np.ndarray, center: np.ndarray) -> np.ndarray:
    """Spherical eye UVs for sclera/iris sampling and cornea parallax."""
    direction = np.asarray(vertices, dtype=np.float64) - np.asarray(center, dtype=np.float64)
    direction /= np.maximum(np.linalg.norm(direction, axis=1, keepdims=True), 1e-12)
    u = np.mod(np.arctan2(-direction[:, 2], direction[:, 0]) / (2 * math.pi) + 1.0, 1.0)
    v = np.arccos(np.clip(-direction[:, 1], -1.0, 1.0)) / math.pi
    return np.stack((u, v), axis=1).astype(np.float32)


def _alpha_strips(strips: list[tuple[float, float, float, float]], *, thickness: float, steps: int):
    vertices: list[list[float]] = []
    uvs: list[list[float]] = []
    faces: list[tuple[int, int, int]] = []
    alpha: list[float] = []
    for x0, y, z, width in strips:
        start = len(vertices)
        for i in range(steps + 1):
            t = i / steps
            x = x0 + width * t
            arch = math.sin(math.pi * t)
            yline = y - 0.006 * arch
            for side in (-1.0, 1.0):
                vertices.append([x, yline + side * thickness * 0.5, z])
                uvs.append([t, (side + 1.0) * 0.5])
                alpha.append(float(math.sin(math.pi * t) ** 0.45))
        for i in range(steps):
            a = start + 2 * i
            faces.extend(((a, a + 2, a + 1), (a + 1, a + 2, a + 3)))
    return (np.asarray(vertices, dtype=np.float32), np.asarray(faces, dtype=np.int32),
            np.asarray(uvs, dtype=np.float32), np.asarray(alpha, dtype=np.float32))


def _hair_cards(lo: np.ndarray, hi: np.ndarray):
    span = hi - lo
    strips = []
    for side in (-1.0, 1.0):
        strips.append((side * 0.015, lo[1] + 0.06 * span[1], (lo[2] + hi[2]) * 0.56, 0.042))
    return _alpha_strips(strips, thickness=0.014, steps=12)


def _jaw_pivot(vertices: np.ndarray) -> np.ndarray:
    lo, hi = vertices.min(axis=0), vertices.max(axis=0)
    span = hi - lo
    return np.array([0.0, lo[1] + 0.72 * span[1] - 0.006, lo[2] + 0.22 * span[2] + 0.016])


def _rotate_about_x(points: np.ndarray, angle: float, pivot: np.ndarray) -> np.ndarray:
    relative = np.asarray(points, dtype=np.float64) - pivot
    cosine, sine = math.cos(angle), math.sin(angle)
    rotation = np.array([[1.0, 0.0, 0.0], [0.0, cosine, -sine], [0.0, sine, cosine]])
    return (relative @ rotation.T + pivot).astype(np.float32)


def _analytic_fallback_head() -> tuple[np.ndarray, np.ndarray]:
    """Small local ellipsoid head used only when no pinned MakeHuman data is installed."""
    rings, segments = 48, 64
    verts = [np.array([0.0, -0.105, 0.0])]
    for ring in range(1, rings):
        theta = math.pi * ring / rings
        for segment in range(segments):
            phi = 2 * math.pi * segment / segments
            x = 0.083 * math.sin(theta) * math.cos(phi)
            y = 0.0525 - 0.1575 * math.cos(theta)
            z = 0.092 * math.sin(theta) * math.sin(phi)
            # Camera-facing half: a restrained nasal bridge, cheeks, and chin are analytic additions.
            front = max(0.0, -math.sin(phi))
            nose = math.exp(-0.5 * ((x / 0.012) ** 2 + ((y - 0.047) / 0.028) ** 2))
            cheek = math.exp(-0.5 * (((abs(x) - 0.043) / 0.025) ** 2 + ((y - 0.080) / 0.025) ** 2))
            z -= front * (0.020 * nose + 0.004 * cheek)
            verts.append(np.array([x, y, z]))
    bottom = len(verts)
    verts.append(np.array([0.0, 0.210, 0.0]))
    faces: list[tuple[int, int, int]] = []
    for j in range(segments):
        faces.append((0, 1 + (j + 1) % segments, 1 + j))
    for ring in range(rings - 2):
        a = 1 + ring * segments
        b = a + segments
        for j in range(segments):
            j1 = (j + 1) % segments
            faces.extend(((a + j, a + j1, b + j), (a + j1, b + j1, b + j)))
    last = 1 + (rings - 2) * segments
    for j in range(segments):
        faces.append((last + j, last + (j + 1) % segments, bottom))
    return np.asarray(verts, dtype=np.float32), np.asarray(faces, dtype=np.int32)


def _local_makehuman_template() -> tuple[np.ndarray, np.ndarray, np.ndarray | None, np.ndarray | None, str]:
    """Use an installed MakeHuman build or fully cached pinned data, without network access."""
    from roop_3d.reconstruction.makehuman_build import ASSET_NAME as MH_ASSET_NAME
    from roop_3d.reconstruction.makehuman_build import DEFAULT_ASSET_DIR as MH_ASSET_DIR
    from roop_3d.reconstruction.makehuman_head import MakeHumanHeadModel

    head_path = MH_ASSET_DIR / MH_ASSET_NAME
    if not head_path.is_file():
        from roop_3d.reconstruction import makehuman_build as builder
        cache = MH_ASSET_DIR / "sources"
        if all((cache / rel).is_file() for rel in builder._all_paths()):
            builder.build_asset()
    if head_path.is_file():
        model = MakeHumanHeadModel.load(head_path)
        return (model.base_mesh.vertices, model.base_mesh.faces, model.base_mesh.uvs,
                model.shape_basis, "makehuman_cc0")
    vertices, faces = _analytic_fallback_head()
    return vertices, faces, None, None, "analytic_cc0_offline_fallback"


def build_anatomical_pack(path: Path | str = DEFAULT_ASSET_PATH) -> Path:
    """Synthesize the complete pack from local CC0 data, with a network-free fallback."""
    vertices, faces, uvs, legacy_basis, source = _local_makehuman_template()
    pack = AnatomicalFullHeadAsset.from_template(vertices, faces, uvs=uvs,
                                                 legacy_shape_basis=legacy_basis, template_source=source)
    return pack.save(path)


