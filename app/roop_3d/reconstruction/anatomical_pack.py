"""License-clean, procedural anatomical extensions for the MakeHuman CC0 head.

The pack contains 60 orthogonal craniofacial displacement fields and small
procedural anatomical meshes.  It uses the MakeHuman *data* asset when one is
already available locally; when it is not, an analytic head surface is
synthesized without downloading files.  No Blender modules or add-on code are
used.

All coordinates use the MakeHuman builder's OpenCV head frame in metres:
x is image-right, y is down, and the face points toward -z.  Jaw and soft
tissue routines are ordinary NumPy transforms so callers can use them in any
renderer.
"""
